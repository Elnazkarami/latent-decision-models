"""Two-step RL models: all tests use synthetic schedules and simulated agents."""

import numpy as np
import pandas as pd
import pytest

from latent_decision_models import two_step_model as ts


def _stack(n):
    """``n`` synthetic sessions as one schedule (2n runs)."""
    parts = [ts.synthetic_schedule(seed=i) for i in range(n)]
    return ts.Schedule(**{k: np.concatenate([getattr(p, k) for p in parts])
                          for k in ts.Schedule.__dataclass_fields__})


@pytest.mark.parametrize("model", list(ts.MODELS))
def test_theta_round_trip(model):
    rng = np.random.default_rng(0)
    p = ts.sample_params(model, rng)
    q = ts.from_theta(ts.to_theta(p, model), model)
    assert q.keys() == p.keys()
    np.testing.assert_allclose(list(q.values()), list(p.values()), rtol=1e-6, atol=1e-6)


def test_outcome_follows_contingency_rule():
    s = ts.synthetic_schedule(seed=3)
    t = 5
    for c in (0, 1):
        choice = np.full(2, c)
        pad, planet, win = ts.outcome(s, t, choice)
        assert (pad == s.pad_if[:, t, c]).all() and (planet == pad // 2).all()
        expect = np.where(s.contingency[:, t] == 1, s.draws[np.arange(2), t, pad],
                          s.draws[:, t, 2 * c])
        assert (win == expect).all()


def test_synthetic_schedule_structure():
    s = ts.synthetic_schedule(seed=1)
    common = (s.pad_if // 2) == np.array([0, 1])  # ship a commonly reaches planet a
    assert 0.6 < common.mean() < 0.8
    assert (s.pad_if[..., 0] // 2 != s.pad_if[..., 1] // 2).all()  # ships reach different planets
    cont = s.contingency.ravel()
    assert (np.diff(cont) != 0).sum() == 1  # one contingency switch per session


def test_likelihood_is_normalised():
    """P(left) + P(right) = 1: scoring each choice of a simulated run sums to 1 per trial."""
    s = ts.synthetic_schedule(seed=0, n_runs=1, n_trials=10)
    params = {"alpha": 0.4, "beta": 4.0, "w": 0.5, "stick": 0.3}
    d = ts.simulate(s, "hybrid", params, seed=1)
    for t in range(10):
        total = 0.0
        for c in (0, 1):
            alt = ts.TwoStepData(**{k: getattr(d, k).copy() for k in d.__dataclass_fields__})
            alt.choice[0, t] = c
            alt.scored[:] = False
            alt.scored[0, t] = True
            total += np.exp(ts.loglik(params, "hybrid", alt))
        assert total == pytest.approx(1.0)


def test_mf_and_mb_are_limits_of_hybrid():
    s = ts.synthetic_schedule(seed=2)
    d = ts.simulate(s, "hybrid", {"alpha": 0.5, "beta": 5, "w": 0.5, "stick": 0.2}, seed=0)
    base = {"alpha": 0.3, "beta": 3.0, "stick": 0.1}
    assert ts.loglik(base, "mf", d) == pytest.approx(ts.loglik({**base, "w": 0.0}, "hybrid", d))
    assert ts.loglik(base, "mb", d) == pytest.approx(ts.loglik({**base, "w": 1.0}, "hybrid", d))
    both = {**base, "w_stimulus": 0.3, "w_state": 0.3}
    assert ts.loglik(both, "hybrid_contingency", d) == pytest.approx(
        ts.loglik({**base, "w": 0.3}, "hybrid", d))


def test_stay_signatures():
    """MF agents show a reward main effect; MB agents a reward x transition interaction."""
    big = _stack(100)
    mf = ts.stay_summary(ts.simulate(big, "mf", {"alpha": 0.6, "beta": 8, "stick": 0}, seed=0))
    mb = ts.stay_summary(ts.simulate(big, "mb", {"alpha": 0.6, "beta": 8, "stick": 0}, seed=0))
    assert (mf["reward_effect"] > 0.1).all() and (mf["interaction"].abs() < 0.08).all()
    assert (mb["interaction"] > 0.1).all()


def test_parameter_recovery_known_answer():
    sched = _stack(4)
    true = {"alpha": 0.5, "beta": 6.0, "w": 0.7, "stick": 0.4}
    d = ts.simulate(sched, "hybrid", true, seed=4)
    est = ts.fit(d, "hybrid", n_starts=2)["params"]
    assert abs(est["alpha"] - 0.5) < 0.2 and abs(est["w"] - 0.7) < 0.2
    assert 3 < est["beta"] < 12 and abs(est["stick"] - 0.4) < 0.3


def test_heldout_runs_never_scores_training_run():
    d = ts.simulate(ts.synthetic_schedule(seed=5), "mf",
                    {"alpha": 0.5, "beta": 5, "stick": 0.2}, seed=0)
    ho = ts.heldout_runs(d, "mf", n_starts=1)
    assert ho["heldout_trials"] == d.n_scored
    assert ho["heldout_loglik"] < 0


def _fake_trials(n_subjects=4, seed=0):
    """A trial table in the adapter's format, generated by an MB-weighted agent."""
    frames = []
    for i in range(n_subjects):
        s = ts.synthetic_schedule(seed=seed + i, subject=f"S{i}")
        d = ts.simulate(s, "hybrid", {"alpha": 0.5, "beta": 6, "w": 0.7, "stick": 0.3},
                        seed=i)
        for r in range(2):
            ok = d.choice[r] >= 0
            frames.append(pd.DataFrame({
                "subject": f"S{i}", "run": f"run-{r + 1}", "trial_index": np.arange(77),
                "choice": np.where(ok, d.choice[r] + 1, np.nan),
                "planet": np.where(ok, d.planet[r] + 1, np.nan),
                "reward_binary": d.win[r], "reward_magnitude": d.win[r] * 50,
                "rare_transition": d.rare[r],
                "reward_contingency": np.where(s.contingency[r] == 1, "state", "stimulus"),
                "response_time_seconds": 0.5, "valid_trial": ok,
                "pad_if_left": s.pad_if[r, :, 0] + 1, "pad_if_right": s.pad_if[r, :, 1] + 1,
                **{f"reward_draw_pad{k + 1}": s.draws[r, :, k] for k in range(4)},
                "magnitude_scale": s.magnitude[r],
                "pad_transition_probability": s.reliability[r]}))
    return pd.concat(frames, ignore_index=True)


def test_prepare_and_schedule_from_trials_round_trip():
    trials = _fake_trials(2)
    d = ts.prepare(trials)
    s = ts.schedule_from_trials(trials)
    assert d.choice.shape == (4, 77) and list(d.run) == ["run-1", "run-2"] * 2
    for t in range(77):
        _, planet, win = ts.outcome(s, t, d.choice[:, t])
        assert (planet == d.planet[:, t]).all() and (win == d.win[:, t]).all()
    fast = trials.assign(response_time_seconds=0.1)
    assert ts.prepare(fast, min_rt=0.15).n_scored == 0
    assert ts.prepare(fast, min_rt=None).n_scored == d.n_scored


def test_compare_structure():
    res = ts.compare(_fake_trials(4), models=("mf", "hybrid"), reference="hybrid",
                     n_starts=1, n_folds=2, n_boot=50, n_rep=2)
